// You are given a string s consisting of lowercase English letters.

// Return an integer denoting the maximum number of substrings you can split s into such that each substring starts with a distinct character (i.e., no two substrings start with the same character).

//_________________________________________________________________________________________________________________________________________________________________________________________________________________________

// Example 1:

// Input: s = "abab"

// Output: 2

// Explanation:

// Split "abab" into "a" and "bab".
// Each substring starts with a distinct character i.e 'a' and 'b'. Thus, the answer is 2.

// Example 2:

// Input: s = "abcd"

// Output: 4

// Explanation:

// Split "abcd" into "a", "b", "c", and "d".
// Each substring starts with a distinct character. Thus, the answer is 4.

// Example 3:

// Input: s = "aaaa"

// Output: 1

// Explanation:

// All characters in "aaaa" are 'a'.
// Only one substring can start with 'a'. Thus, the answer is 1.

//_________________________________________________________________________________________________________________________________________________________________________________________________________________________
 
// Constraints:

// 1 <= s.length <= 105
// s consists of lowercase English letters.
//_________________________________________________________________________________________________________________________________________________________________________________________________________________________
#include<iostream>
#include<vector>
#include<unordered_set>
#include<string>
using namespace std;

//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
// Method 1
//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
class Solution {
public:
    int maxDistinct(string s) {
        return unordered_set(s.begin(),s.end()).size();
    }
};
//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
// Method 2
//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
class Solution {
public:
    int maxDistinct(string s) {
        vector<char> characters;
        int result = 0;
        for(auto& c:s){
            if(find(characters.begin(),characters.end(),c)!=characters.end()){
                continue;
            }
            else{
                characters.push_back(c);
                result += 1;

            }

        }
        return result;
    }
};

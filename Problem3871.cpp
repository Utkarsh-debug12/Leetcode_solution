// You are given an integer n.

// Return the total number of commas used when writing all integers from [1, n] (inclusive) in standard number formatting.

// In standard formatting:

// A comma is inserted after every three digits from the right.
// Numbers with fewer than 4 digits contain no commas.
//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
 

// Example 1:

// Input: n = 1002

// Output: 3

// Explanation:

// The numbers "1,000", "1,001", and "1,002" each contain one comma, giving a total of 3.

// Example 2:

// Input: n = 998

// Output: 0

// Explanation:

// ​​​​​​​All numbers from 1 to 998 have fewer than four digits. Therefore, no commas are used.

//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________

// Constraints:

// 1 <= n <= 1015
//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
#include<iostream>
#include<vector>
using namespace std;

//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
// Method 1
//_____________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________________
class Solution {
public:
    long long countCommas(long long n) {
        long long result;
        if(n<1000){
            result =  0;
        }
        else if(n>=1000 && n< pow(10,6)){
            result =  n-999;
        }
        else if(n>=pow(10,6) && n<pow(10,9)){
            result =  pow(10,6)-1000+(n-999999)*2;
        }
        else if(n>=pow(10,9)&& n<pow(10,12)){
            result =  pow(10,6)-1000+(pow(10,9)-1000000)*2+(n-999999999)*3;
        }
        else if(n>=pow(10,12) && n<pow(10,15)){
            result =  (pow(10,6)-1000)+(pow(10,9)-1000000)*2+(pow(10,12)-1000000000)*3+(n-999999999999)*4;
        }
        else if(n == pow(10,15)){
            result =  (pow(10,6)-1000)+((pow(10,9)-1000000)*2)+((pow(10,12)-1000000000)*3)+((pow(10,15)-1000000000000)*4)+5;
        }
        return result;
    }
};
